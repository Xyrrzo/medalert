-- Remove any pre-existing permissive policies on these tables so this migration is the complete policy set.
do $$ declare p record; begin
  for p in select schemaname, tablename, policyname from pg_policies
    where schemaname = 'public' and tablename in ('profiles','health_units','appointments','announcements','symptom_reports','reminders')
  loop execute format('drop policy if exists %I on %I.%I', p.policyname, p.schemaname, p.tablename); end loop;
end $$;

