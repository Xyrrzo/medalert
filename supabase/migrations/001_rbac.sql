create or replace function public.current_app_role()
returns public.app_role language sql stable security definer set search_path = public
as $$ select role from public.profiles where id = auth.uid() $$;

create or replace function public.create_patient_profile()
returns trigger language plpgsql security definer set search_path = public
as $$ begin
  insert into public.profiles (id, full_name, role) values (new.id, new.raw_user_meta_data ->> 'full_name', 'PATIENT')
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile after insert on auth.users for each row execute function public.create_patient_profile();

create or replace function public.protect_profile_role()
returns trigger language plpgsql security definer set search_path = public
as $$ begin
  if tg_op = 'DELETE' then
    if old.role = 'ADMIN' and (select count(*) from public.profiles where role = 'ADMIN') <= 1 then
      raise exception 'Cannot remove the last ADMIN';
    end if;
    return old;
  end if;
  if new.role is distinct from old.role then
    if auth.uid() is not null and public.current_app_role() is distinct from 'ADMIN'::public.app_role then
      raise exception 'Only ADMIN can change roles';
    end if;
    if old.role = 'ADMIN' and new.role <> 'ADMIN' and (select count(*) from public.profiles where role = 'ADMIN') <= 1 then
      raise exception 'Cannot demote the last ADMIN';
    end if;
  end if;
  return new;
end $$;
drop trigger if exists protect_profile_role on public.profiles;
create trigger protect_profile_role before update or delete on public.profiles for each row execute function public.protect_profile_role();

create or replace function public.protect_appointment_update()
returns trigger language plpgsql security definer set search_path = public
as $$ begin
  if public.current_app_role() = 'PATIENT' then
    if old.user_id <> auth.uid() or new.status <> 'cancelled' or old.status = 'cancelled'
       or (to_jsonb(new) - 'status') is distinct from (to_jsonb(old) - 'status') then
      raise exception 'Patients may only cancel their own appointments';
    end if;
  elsif public.current_app_role() in ('MEDSTAFF', 'ADMIN') then
    if new.status not in ('confirmed', 'completed', 'rejected') or old.status <> 'pending'
       or (to_jsonb(new) - 'status') is distinct from (to_jsonb(old) - 'status') then
      raise exception 'Staff may only resolve pending appointment status';
    end if;
  else raise exception 'Not authorized'; end if;
  return new;
end $$;
drop trigger if exists protect_appointment_update on public.appointments;
create trigger protect_appointment_update before update on public.appointments for each row execute function public.protect_appointment_update();

create or replace function public.protect_symptom_report_update()
returns trigger language plpgsql security definer set search_path = public
as $$ begin
  if public.current_app_role() not in ('MEDSTAFF', 'ADMIN') or (to_jsonb(new) - 'handled') is distinct from (to_jsonb(old) - 'handled') then
    raise exception 'Only staff may update handled status';
  end if;
  return new;
end $$;
drop trigger if exists protect_symptom_report_update on public.symptom_reports;
create trigger protect_symptom_report_update before update on public.symptom_reports for each row execute function public.protect_symptom_report_update();

