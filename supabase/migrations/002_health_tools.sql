-- Personal Health Tools data. Each account can access only its own records.
create table if not exists public.user_health_profiles (
  user_id uuid not null references auth.users(id) on delete cascade,
  tool_key text not null,
  value text not null,
  updated_at timestamptz not null default now(),
  primary key (user_id, tool_key)
);

create table if not exists public.user_health_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  tool_key text not null,
  value text not null,
  created_at timestamptz not null default now()
);

create index if not exists user_health_entries_owner_tool_created_idx
  on public.user_health_entries (user_id, tool_key, created_at desc);

alter table public.user_health_profiles enable row level security;
alter table public.user_health_entries enable row level security;

drop policy if exists user_health_profiles_owner_all on public.user_health_profiles;
create policy user_health_profiles_owner_all
  on public.user_health_profiles for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

drop policy if exists user_health_entries_owner_all on public.user_health_entries;
create policy user_health_entries_owner_all
  on public.user_health_entries for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

grant select, insert, update, delete on public.user_health_profiles to authenticated;
grant select, insert, update, delete on public.user_health_entries to authenticated;
grant usage, select on sequence public.user_health_entries_id_seq to authenticated;
